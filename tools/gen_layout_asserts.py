#!/usr/bin/env python3
"""Generate layout checks from header offset annotations.

Headers annotate members with their offset in the original binary:

    class CGameSprite : public CGameAIBase {
        /* 05A0 */ CString m_sName;

This script emits tests/unit/test_layout.cpp: a table of
(Class::member, offsetof(Class, member), annotated offset) for every annotated
data member, and a unit test that lists every mismatch with its real offset.

Mismatches listed in tests/layout/known_mismatches.txt (one "Class::member"
or "Class" per line) are reported but don't fail the test. Remove entries as
you fix them. A new mismatch fails the test.

CMake runs this at build time (output goes to the build folder).

Usage: py -I tools/gen_layout_asserts.py [--out FILE] [--report]
  --report  print annotated member counts per class and exit
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "src"
OUT = REPO / "tests" / "unit" / "test_layout.cpp"
KNOWN = REPO / "tests" / "layout" / "known_mismatches.txt"

CLASS_RE = re.compile(r"^\s*(class|struct)\s+(?:__declspec\([^)]*\)\s+)?(\w+)\s*(?::[^{;]*)?\{?\s*$")
MEMBER_RE = re.compile(r"^\s*/\*\s*([0-9A-Fa-f]{4,5})\s*\*/\s*(?!virtual\b)([^;()]*?)\b(\w+)\s*(\[[^\]]*\])*\s*;")
TEMPLATE_RE = re.compile(r"^\s*template\s*<")

TEST_TEMPLATE = r'''
namespace {

struct LayoutEntry {
    const char* cls;
    const char* name;
    size_t actual;
    size_t expected;
};

const LayoutEntry kLayout[] = {
@ENTRIES@
};

const char* const kKnown[] = {
@KNOWN@
    "",
};

} // namespace

TEST_CASE("annotated member offsets match the original layout")
{
    std::set<std::string> known(std::begin(kKnown), std::end(kKnown));
    int unexpected = 0;
    int expected = 0;
    for (const LayoutEntry& e : kLayout) {
        if (e.actual == e.expected) {
            continue;
        }
        bool isKnown = known.count(e.name) != 0 || known.count(e.cls) != 0;
        std::printf("%s %s: actual 0x%zX, annotated 0x%zX\n", isKnown ? "known" : "NEW  ", e.name, e.actual, e.expected);
        if (isKnown) {
            expected++;
        } else {
            unexpected++;
        }
    }
    MESSAGE("layout: " << (sizeof(kLayout) / sizeof(kLayout[0])) << " members, " << expected << " known mismatches, " << unexpected << " new");
    CHECK(unexpected == 0);
}
'''


def parse_header(path: Path):
    """Yield (class, member, offset) for annotated data members of top-level classes."""
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    stack: list[str | None] = []
    pending: str | None = None
    template_pending = False
    for line in lines:
        code = line.split("//", 1)[0]
        if TEMPLATE_RE.match(code):
            template_pending = True
        m = CLASS_RE.match(code)
        if m and not code.rstrip().endswith(";"):
            # Skip templates: offsetof needs concrete types.
            pending = None if template_pending else m.group(2)
            template_pending = False
        mm = MEMBER_RE.match(line)
        if mm and stack and stack[-1] and len([s for s in stack if s]) == 1:
            yield stack[-1], mm.group(3), int(mm.group(1), 16)
        for ch in code:
            if ch == "{":
                stack.append(pending)
                pending = None
            elif ch == "}" and stack:
                stack.pop()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", action="store_true")
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()

    known: set[str] = set()
    if KNOWN.exists():
        known = {l.split("#", 1)[0].strip() for l in KNOWN.read_text(encoding="utf-8").splitlines()} - {""}

    entries: dict[str, list[tuple[str, int]]] = {}
    headers: dict[str, str] = {}
    for h in sorted(SRC.rglob("*.h")):
        for cls, member, off in parse_header(h):
            entries.setdefault(cls, []).append((member, off))
            headers.setdefault(cls, h.relative_to(SRC).as_posix())

    if args.report:
        for cls, mems in sorted(entries.items(), key=lambda t: -len(t[1])):
            print(f"{len(mems):5} {cls} ({headers[cls]})")
        return 0

    rows = []
    for cls in sorted(entries):
        seen = set()
        for member, off in entries[cls]:
            if member in seen:
                continue
            seen.add(member)
            rows.append(f'    {{ "{cls}", "{cls}::{member}", offsetof({cls}, {member}), 0x{off:X} }},')

    head = [
        "// Generated by tools/gen_layout_asserts.py. Do not edit.",
        "// Checks that annotated member offsets match the original layout.",
        "",
        '#include "test.h"',
        "",
        "#include <cstddef>",
        "#include <cstdio>",
        "#include <iterator>",
        "#include <set>",
        "#include <string>",
        "",
        "// Allow offsetof on private and protected members. Nothing here calls",
        "// member functions, so access-dependent name mangling doesn't matter.",
        "#define private public",
        "#define protected public",
        "",
        *[f'#include "{h}"' for h in sorted(set(headers.values()))],
        "",
        "#undef private",
        "#undef protected",
        "",
        "#pragma warning(disable : 4995 4996 4200)",
    ]
    body = TEST_TEMPLATE.replace("@ENTRIES@", "\n".join(rows)).replace(
        "@KNOWN@", "\n".join(f'    "{k}",' for k in sorted(known)))
    out = args.out.resolve()
    out.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(head) + "\n" + body
    # Only rewrite when content changes, so builds stay incremental.
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        out.write_text(text, encoding="utf-8")
    print(f"wrote {out}: {len(rows)} members, {len(known)} known mismatches, {len(entries)} classes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
